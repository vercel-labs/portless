    const { caPath } = ensureCerts(tmpDir);
    const trustDir = path.join(tmpDir, "linux-trust");
    const installedCA = path.join(trustDir, "portless-ca.crt");
    const config = { certDir: trustDir, updateCommand: "refresh-linux-trust" };
